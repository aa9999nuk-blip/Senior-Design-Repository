def make_poster(all_results, save_path=None, dpi=POSTER_DPI,
                title="PPG Cuffless BP Estimation"):
    """
    Produces a single combined poster figure AND saves every panel
    individually via save_figures().

    Layout (4 columns × 4 rows):
      Row 0:  [BA SBP] [BA DBP] [Scatter SBP] [Scatter DBP]
      Row 1:  [Violin] [Cumulative accuracy] [Per-session table (spans 2)]
      Row 2:  [Per-session error bars (spans 3)] [Summary stats]
      Row 3:  [Clinical-style summary table (spans all 4)]
    """
    sbp_rows, dbp_rows = _prep_rows(all_results)

    # ── Save individual PNGs first ────────────────────────────
    save_figures(all_results, dpi=dpi, title=title)

    # ── Build combined poster ─────────────────────────────────
    fig = plt.figure(figsize=(26, 20), facecolor=DARK_BG)
    gs  = gridspec.GridSpec(4, 4, figure=fig, hspace=0.55, wspace=0.40,
                            left=0.06, right=0.97, top=0.93, bottom=0.04)

    fig.text(0.5, 0.967, title, ha="center", va="top",
             fontsize=24, fontweight="bold", color=TEXT_COL, fontfamily="monospace")
    fig.text(0.5, 0.945,
             f"n = {len(all_results)} test sessions  |  "
             "IR wrist PPG → BP  |  Stacked ensemble (RF + ENet + XGB + GBM) + delta calibration",
             ha="center", va="top", fontsize=12, color=MUTED_COL, fontfamily="monospace")

    ax_ba_sbp = fig.add_subplot(gs[0, 0]); _bland_altman(ax_ba_sbp, sbp_rows, "SBP", SBP_COL_P)
    ax_ba_dbp = fig.add_subplot(gs[0, 1]); _bland_altman(ax_ba_dbp, dbp_rows, "DBP", DBP_COL_P)
    ax_scatter = fig.add_subplot(gs[0, 2:4]); _scatter_pred_true(ax_scatter, sbp_rows, dbp_rows)

    ax_violin = fig.add_subplot(gs[1, 0]); _error_violin(ax_violin, sbp_rows, dbp_rows)
    ax_cum    = fig.add_subplot(gs[1, 1]); _cumulative_accuracy(ax_cum, sbp_rows, dbp_rows)
    ax_table  = fig.add_subplot(gs[1, 2:4]); _session_table(ax_table, all_results)

    ax_bar    = fig.add_subplot(gs[2, 0:3]); _per_session_bars(ax_bar, all_results)
    ax_stats  = fig.add_subplot(gs[2, 3]);   _summary_stats_panel(ax_stats, sbp_rows, dbp_rows)

    ax_clin   = fig.add_subplot(gs[3, :]); _clinical_table(ax_clin, sbp_rows, dbp_rows, all_results)

    if save_path:
        fig.savefig(save_path, dpi=dpi, bbox_inches="tight",
                    facecolor=DARK_BG, edgecolor="none")
        print(f"\n  Combined poster saved → {save_path}  ({dpi} dpi)")

    plt.show()
    return fig

