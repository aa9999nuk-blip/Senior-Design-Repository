class StackedEnsemble:
    def __init__(self):
        self.base={
            "rf":  RandomForestRegressor(**RF_PARAMS),
            "enet":Pipeline([("m",ElasticNetCV(l1_ratio=ENET_L1,cv=5,random_state=42,max_iter=20000))]),
            "xgb": xgb.XGBRegressor(**XGB_PARAMS),
            "gbm": GradientBoostingRegressor(**GBM_PARAMS),
        }
        self.meta=RidgeCV(alphas=STACK_ALPHAS); self.fitted=False

    def fit(self,X_train,y_train,n_folds=5):
        kf=KFold(n_splits=n_folds,shuffle=True,random_state=42)
        oof=np.zeros((len(X_train),len(self.base)))
        for fold,(tr_i,val_i) in enumerate(kf.split(X_train)):
            for j,(nm,m) in enumerate(self.base.items()):
                m_=copy.deepcopy(m);m_.fit(X_train[tr_i],y_train[tr_i])
                oof[val_i,j]=m_.predict(X_train[val_i])
        self.meta.fit(oof,y_train)
        for m in self.base.values(): m.fit(X_train,y_train)
        self.fitted=True; return self

    def predict(self,X):
        bp=np.column_stack([m.predict(X) for m in self.base.values()])
        return self.meta.predict(bp)

    def predict_with_uncertainty(self,X):
        bp=np.column_stack([m.predict(X) for m in self.base.values()])
        return self.meta.predict(bp),np.std(bp,axis=1)

