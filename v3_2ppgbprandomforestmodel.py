def infer_fs(df):
    if "timestamp_ms" in df.columns:
        dt=df["timestamp_ms"].diff().median()
        if dt and dt>0: return 1000.0/dt
    return 100.0

def bandpass(x,fs,low=0.5):
    high=min(8.0,fs/2.0-0.5)
    if high<=low: return x.astype(float)
    b,a=butter(4,[low/(fs/2),high/(fs/2)],btype="band")
    return filtfilt(b,a,x.astype(float))

def normalise(x):
    lo,hi=np.min(x),np.max(x); return (x-lo)/(hi-lo+EPS)

