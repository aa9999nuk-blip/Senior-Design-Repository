    print("MULTI-TEST EVALUATION")
    print("="*68)
    print(f"{'Label':<20} {'Pred SBP':>9} {'True SBP':>9} {'Err SBP':>8} "
          f"{'Pred DBP':>9} {'True DBP':>9} {'Err DBP':>8} {'Win':>4}")
    print("─"*80)

    all_results = []
    for path, true_sbp, true_dbp, label in test_sessions:
        try:
            res, ppg, fs, n_total = predict_file(cal_obj, path)
            if res is None:
                print(f"  {label:<18} NO GOOD WINDOWS"); continue

            pred_sbp = res["sbp"]["pred"]
            pred_dbp = res["dbp"]["pred"]
            err_sbp  = (pred_sbp - true_sbp) if (true_sbp and np.isfinite(pred_sbp)) else None
            err_dbp  = (pred_dbp - true_dbp) if (true_dbp and np.isfinite(pred_dbp)) else None

            row = dict(label=label, path=path,
                       true_sbp=true_sbp, true_dbp=true_dbp,
                       pred_sbp=pred_sbp, pred_dbp=pred_dbp,
                       err_sbp=err_sbp,   err_dbp=err_dbp,
                       ci_sbp=(res["sbp"]["ci_low"], res["sbp"]["ci_high"]),
                       ci_dbp=(res["dbp"]["ci_low"], res["dbp"]["ci_high"]),
                       n_windows=res["dbp"]["n_windows"],
                       ppg=ppg, fs=fs)
            all_results.append(row)

            def fmt(v): return f"{v:+6.1f}" if v is not None else "  N/A "
            print(f"  {label:<18} {pred_sbp:>9.1f} {str(true_sbp):>9} {fmt(err_sbp):>8} "
                  f"{pred_dbp:>9.1f} {str(true_dbp):>9} {fmt(err_dbp):>8} "
                  f"{res['dbp']['n_windows']:>4}")
        except Exception as e:
            print(f"  {label:<18} ERROR: {e}")

    # Aggregate stats
    sbp_errs = [abs(r["err_sbp"]) for r in all_results if r["err_sbp"] is not None]
    dbp_errs = [abs(r["err_dbp"]) for r in all_results if r["err_dbp"] is not None]
    print("─"*80)
    if sbp_errs:
        print(f"  SBP  MAE={np.mean(sbp_errs):.1f}  RMSE={np.sqrt(np.mean(np.array(sbp_errs)**2)):.1f}  "
              f"max={np.max(sbp_errs):.1f} mmHg  (n={len(sbp_errs)})")
    if dbp_errs:
        print(f"  DBP  MAE={np.mean(dbp_errs):.1f}  RMSE={np.sqrt(np.mean(np.array(dbp_errs)**2)):.1f}  "
              f"max={np.max(dbp_errs):.1f} mmHg  (n={len(dbp_errs)})")
    print(f"  AAMI grade A threshold: ≤5 mmHg MAE")
    return all_results

