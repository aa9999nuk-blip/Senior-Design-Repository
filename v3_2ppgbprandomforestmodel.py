def run_calibration(trained, cal_sessions):
    cal_records=[]
    for path,sbp_label,dbp_label in cal_sessions:
        try:
            ppg,fs,_,_,col=load_ppg(path)
            print(f"  {os.path.basename(path)}  col={col}  fs={fs:.1f}Hz  dur={len(ppg)/fs:.1f}s")
            good,n_total=extract_windows(ppg,fs,verbose=True)
            print(f"    → {len(good)}/{n_total} windows accepted")
            if not good: continue
            fd=aggregate_windows(good)
            cal_records.append({"feat":fd,"sbp":sbp_label,"dbp":dbp_label,"file":os.path.basename(path)})
        except Exception as e:
            print(f"  Cal skip {os.path.basename(path)}: {e}")

    if not cal_records: raise RuntimeError("No usable cal sessions.")

    cal_obj={"trained":trained,"records":cal_records,"cal":{}}
    ref=cal_records[0]

    for bp_key in ["sbp","dbp"]:
        delta_key=f"{bp_key}_delta"
        y_true_d=[];y_pred_d=[];y_true_a=[];y_pred_a=[]
        for rec in cal_records[1:]:
            if rec[bp_key] is None or ref[bp_key] is None: continue
            true_delta=rec[bp_key]-ref[bp_key]
            feat_d={}
            for k in ref["feat"]:
                rv=ref["feat"].get(k,np.nan);sv=rec["feat"].get(k,np.nan)
                feat_d[f"diff__{k}"]=sv-rv if (np.isfinite(rv) and np.isfinite(sv)) else np.nan
                feat_d[f"ratio__{k}"]=sv/(rv+EPS) if (np.isfinite(rv) and np.isfinite(sv)) else np.nan
                feat_d[f"raw__{k}"]=sv
            if delta_key in trained.get("delta",{}):
                pred_d=_apply_model(trained["delta"][delta_key],feat_d)
                y_pred_d.append(pred_d);y_true_d.append(true_delta)
            if bp_key in trained.get("abs",{}):
                pred_a=_apply_model(trained["abs"][bp_key],rec["feat"])
                y_pred_a.append(pred_a);y_true_a.append(float(rec[bp_key]))

        n_d=len(y_true_d)
        if n_d>=MIN_CAL_FOR_RIDGE:
            y_t=np.array(y_true_d);y_p=np.array(y_pred_d)
            rc=RidgeCV(alphas=RIDGE_ALPHAS,cv=n_d);rc.fit(y_p.reshape(-1,1),y_t)
            cal_obj["cal"][bp_key]={"method":"ridge_delta","ridge_d":rc,"n_d":n_d}
        elif n_d>0:
            offset_d=float(np.mean(np.array(y_true_d)-np.array(y_pred_d)))
            cal_obj["cal"][bp_key]={"method":"offset_delta","offset_d":offset_d,"n_d":n_d}
        elif len(y_true_a)>0:
            offset_a=float(np.mean(np.array(y_true_a)-np.array(y_pred_a)))
            cal_obj["cal"][bp_key]={"method":"offset_abs","offset_a":offset_a}
        else:
            cal_obj["cal"][bp_key]={"method":"none"}

        cal_obj[f"ref_{bp_key}"]=ref[bp_key]
        cal_obj["ref_feat"]=ref["feat"]

    return cal_obj

