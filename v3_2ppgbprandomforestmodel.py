def predict_file(cal_obj, path):
    ppg,fs,_,_,col=load_ppg(path)
    good,n_total=extract_windows(ppg,fs,verbose=True)
    print(f"    → {len(good)}/{n_total} windows accepted")
    if not good: return None, ppg, fs, n_total

    trained=cal_obj["trained"]; ref_feat=cal_obj.get("ref_feat",{})

    results={}
    for bp_key in ["sbp","dbp"]:
        delta_key=f"{bp_key}_delta"; ref_bp=cal_obj.get(f"ref_{bp_key}")
        cal_info=cal_obj["cal"].get(bp_key,{"method":"none"})
        per_win=[]; per_unc=[]

        for wf in good:
            pred_final=None; unc=0.0
            if delta_key in trained.get("delta",{}) and ref_feat and ref_bp is not None:
                feat_d={}
                for k in ref_feat:
                    rv=ref_feat.get(k,np.nan);sv=wf.get(k,np.nan)
                    feat_d[f"diff__{k}"]=sv-rv if (np.isfinite(rv) and np.isfinite(sv)) else np.nan
                    feat_d[f"ratio__{k}"]=sv/(rv+EPS) if (np.isfinite(rv) and np.isfinite(sv)) else np.nan
                    feat_d[f"raw__{k}"]=sv
                obj=trained["delta"][delta_key]
                all_c=obj["all_cols"];sel_i=obj["sel_idx"]
                X_df=pd.DataFrame([feat_d]).reindex(columns=all_c,fill_value=np.nan)
                X_imp=obj["imp"].transform(X_df.values.astype(float))
                X_s=obj["scaler"].transform(X_imp)[:,sel_i]
                pd_arr,unc_arr=obj["stack"].predict_with_uncertainty(X_s)
                pd_val=float(pd_arr[0]);unc=float(unc_arr[0])
                m=cal_info["method"]
                if m=="ridge_delta": pd_cal=float(cal_info["ridge_d"].predict([[pd_val]])[0])
                elif m=="offset_delta": pd_cal=pd_val+cal_info.get("offset_d",0.0)
                else: pd_cal=pd_val
                pred_final=ref_bp+pd_cal
            if pred_final is None and bp_key in trained.get("abs",{}):
                obj=trained["abs"][bp_key]
                X_df=pd.DataFrame([wf]).reindex(columns=obj["all_cols"],fill_value=np.nan)
                X_imp=obj["imp"].transform(X_df.values.astype(float))
                X_s=obj["scaler"].transform(X_imp)[:,obj["sel_idx"]]
                pa,ua=obj["stack"].predict_with_uncertainty(X_s)
                pa=float(pa[0]);unc=float(ua[0])
                m=cal_info["method"]
                pred_final=pa+cal_info.get("offset_a",0.0) if m=="offset_abs" else pa
            if pred_final is not None: per_win.append(pred_final);per_unc.append(unc)

        if not per_win:
            results[bp_key]={"pred":np.nan,"std":np.nan,"ci_low":np.nan,"ci_high":np.nan,
                             "per_window":np.array([]),"n_windows":0}; continue
        preds=np.array(per_win); pred=float(np.mean(preds)); std=float(np.std(preds))
        unc_mean=float(np.mean(per_unc)) if per_unc else std
        half_ci=max(1.96*std,unc_mean)
        results[bp_key]={"pred":pred,"std":std,"ci_low":pred-half_ci,"ci_high":pred+half_ci,
                         "per_window":preds,"n_windows":len(preds)}
    return results, ppg, fs, n_total

