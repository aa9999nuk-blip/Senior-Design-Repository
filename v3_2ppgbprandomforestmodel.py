def run_all_tests(cal_obj, test_sessions):
    """
    Returns a list of result dicts, one per test session.
    Each dict: label, path, true_sbp, true_dbp,
               pred_sbp, pred_dbp, err_sbp, err_dbp,
               ci_sbp, ci_dbp, n_windows, ppg, fs
    """
