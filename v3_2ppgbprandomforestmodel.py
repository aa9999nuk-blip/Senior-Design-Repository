def extract_windows(ppg, fs, verbose=False):
    """
    Slide windows across ppg, run quality gate, extract features from passing windows.
    verbose=True prints a short rejection breakdown (useful for debugging low yield).
    """
    win  = int(WINDOW_SEC * fs)
    step = int(STEP_SEC   * fs)
    if win < 2:
        return [], 0

    windows = [ppg[s:s+win] for s in range(0, len(ppg) - win + 1, step)]

    if verbose:
        n_few_peaks = n_bad_hr = n_high_cv = n_ok = 0
        for w in windows:
            peaks, _ = detect_peaks_ppg(w, fs)
            if len(peaks) < MIN_BEATS_PER_WINDOW: n_few_peaks += 1; continue
            rr = np.diff(peaks) / fs
            if len(rr) < 2: n_few_peaks += 1; continue
            hr = 60.0 / (np.mean(rr) + EPS)
            if not (MIN_HR <= hr <= MAX_HR): n_bad_hr += 1; continue
            cv = np.std(rr) / (np.mean(rr) + EPS)
            if cv > MAX_CV_RR: n_high_cv += 1; continue
            n_ok += 1
        print(f"    Window breakdown: total={len(windows)}  "
              f"ok={n_ok}  few_peaks={n_few_peaks}  bad_hr={n_bad_hr}  "
              f"high_cv={n_high_cv}  (after soft rescue)")

    good = [extract_features(w, fs) for w in windows if window_ok(w, fs)]
    return good, len(windows)

def aggregate_windows(feat_list):
    if not feat_list: return {}
    df=pd.DataFrame(feat_list)
    out={}
    for col in df.columns:
        vals=df[col].astype(float).dropna().values
        out[col]=float(trim_mean(vals,0.1)) if len(vals)>=4 else (float(np.mean(vals)) if len(vals) else np.nan)
    return out

